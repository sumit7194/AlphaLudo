"""High-performance Dataset Loader for V15.3 SL Teacher Shards.

Reads binary packed shards generated by Rust `generate_sl_teacher`:
  Each record (20 bytes):
    - positions:      (4, 4) int8
    - current_player: int8
    - dice_roll:      int8
    - action:         int8
    - target_value:   int8 (+1 or -1)

Encodes dynamically on __getitem__ for V15 GraphTransformer (history_len=1):
  - x:          (1, 15, 15, 3) float32 canonical frame
  - target:     int64 target source cell index in [0, 225)
  - legal_mask: (225,) float32 mask of movable source cells
  - value:      float32 terminal outcome (+1.0 / -1.0)
"""
from __future__ import annotations

import glob
import os
from pathlib import Path
import sys
from typing import List, Optional

_ROOT = Path(__file__).resolve().parent.parent
for _p in (str(_ROOT), str(_ROOT / "td_ludo"), str(_ROOT / "td_ludo_v15")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import numpy as np
import torch
from torch.utils.data import Dataset

import td_ludo_cpp as ludo_cpp
import td_ludo_v15_cpp as v15_cpp
from td_ludo_v15.game.cells import NUM_BOARD_CELLS, cell_to_index, position_to_cell_in_pov
from td_ludo_v15.game.encoder import encode_frame

_BASE_POS = v15_cpp.BASE_POS

SL_RECORD_DTYPE = np.dtype([
    ("positions", np.int8, (4, 4)),
    ("current_player", np.int8),
    ("dice_roll", np.int8),
    ("action", np.int8),
    ("target_value", np.int8),
])


class V153TeacherDataset(Dataset):
    """Memory-mapped / dynamically cached dataset of binary teacher shards."""

    def __init__(self, shard_dir: str | Path, max_shards: Optional[int] = None):
        self.shard_dir = Path(shard_dir)
        self.shard_files = sorted(list(self.shard_dir.glob("shard_*.bin")))
        if max_shards is not None:
            self.shard_files = self.shard_files[:max_shards]

        self.shards: List[np.ndarray] = []
        self.cumulative_sizes: List[int] = []
        total_records = 0

        for sf in self.shard_files:
            file_size = sf.stat().st_size
            if file_size < SL_RECORD_DTYPE.itemsize:
                continue
            num_recs = file_size // SL_RECORD_DTYPE.itemsize
            data = np.memmap(sf, dtype=SL_RECORD_DTYPE, mode="r", shape=(num_recs,))
            self.shards.append(data)
            total_records += num_recs
            self.cumulative_sizes.append(total_records)

        self.total_records = total_records

    def __len__(self) -> int:
        return self.total_records

    def __getitem__(self, idx: int):
        # Binary search for shard
        shard_idx = np.searchsorted(self.cumulative_sizes, idx, side="right")
        offset = idx if shard_idx == 0 else idx - self.cumulative_sizes[shard_idx - 1]
        rec = self.shards[shard_idx][offset]

        cp = int(rec["current_player"])
        dice = int(rec["dice_roll"])
        act = int(rec["action"])
        val = float(rec["target_value"])

        # Reconstruct lightweight C++ state
        state = ludo_cpp.create_initial_state_2p()
        state.player_positions = rec["positions"].tolist()
        state.current_player = cp
        state.current_dice_roll = dice

        # Target cell index in POV
        pos = int(rec["positions"][cp, act])
        c = position_to_cell_in_pov(_BASE_POS if pos == _BASE_POS else pos, cp, cp)
        target_cell_idx = int(cell_to_index(*c))

        # Legal mask over 225 board cells
        legal_mask = np.zeros(NUM_BOARD_CELLS, dtype=np.float32)
        legal_tokens = ludo_cpp.get_legal_moves(state)
        for t in legal_tokens:
            t_pos = int(rec["positions"][cp, t])
            tc = position_to_cell_in_pov(_BASE_POS if t_pos == _BASE_POS else t_pos, cp, cp)
            legal_mask[cell_to_index(*tc)] = 1.0

        # Ensure target is marked legal
        legal_mask[target_cell_idx] = 1.0

        # Encode (1, 15, 15, 3)
        raw_frame = encode_frame(state, pov_player=cp)
        x = np.expand_dims(raw_frame.astype(np.float32), axis=0)

        return {
            "x": torch.from_numpy(x),
            "target": target_cell_idx,
            "legal_mask": torch.from_numpy(legal_mask),
            "target_value": torch.tensor(val, dtype=torch.float32),
        }
